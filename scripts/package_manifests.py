#!/usr/bin/env python3
# SPDX-License-Identifier: MIT
"""Generate a Homebrew formula and Scoop manifest from published release checksums.

Reads the `<archive>.sha256` files of one release (DIGEST, two spaces, FILE NAME),
validates all five native targets, and only then writes `permesh.rb` and
`permesh.json`. Nothing is downloaded; manifests reference existing release assets.
"""
import argparse
import json
import re
import sys
from pathlib import Path

REPOSITORY = "https://github.com/NIPE-Solutions/permesh"
TARGETS = {
    "aarch64-apple-darwin": "tar.gz",
    "x86_64-apple-darwin": "tar.gz",
    "aarch64-unknown-linux-gnu": "tar.gz",
    "x86_64-unknown-linux-gnu": "tar.gz",
    "x86_64-pc-windows-msvc": "zip",
}
DIGEST = re.compile(r"[0-9a-f]{64}")


def archive_name(version, target):
    return f"permesh-{version}-{target}.{TARGETS[target]}"


def archive_url(version, target):
    return f"{REPOSITORY}/releases/download/v{version}/{archive_name(version, target)}"


def read_checksums(directory: Path, version: str) -> dict:
    sums = {}
    for target in TARGETS:
        name = archive_name(version, target)
        path = directory / f"{name}.sha256"
        if not path.is_file():
            raise ValueError(f"missing checksum file: {path.name}")
        fields = path.read_text(encoding="ascii").split()
        if len(fields) != 2 or not DIGEST.fullmatch(fields[0]) or fields[1] != name:
            raise ValueError(f"malformed checksum file: {path.name}")
        sums[target] = fields[0]
    return sums


def homebrew_formula(version: str, sums: dict) -> str:
    def block(target):
        return (
            f'      url "{archive_url(version, target)}"\n'
            f'      sha256 "{sums[target]}"\n'
        )

    return (
        "# SPDX-License-Identifier: MIT\n"
        "# Generated by permesh scripts/package_manifests.py; do not edit by hand.\n"
        "class Permesh < Formula\n"
        '  desc "Know who has access to what: local, read-only access review"\n'
        f'  homepage "{REPOSITORY}"\n'
        f'  version "{version}"\n'
        '  license "MIT"\n'
        "\n"
        "  on_macos do\n"
        f"    on_arm do\n{block('aarch64-apple-darwin')}    end\n"
        f"    on_intel do\n{block('x86_64-apple-darwin')}    end\n"
        "  end\n"
        "\n"
        "  on_linux do\n"
        f"    on_arm do\n{block('aarch64-unknown-linux-gnu')}    end\n"
        f"    on_intel do\n{block('x86_64-unknown-linux-gnu')}    end\n"
        "  end\n"
        "\n"
        "  def install\n"
        '    bin.install "permesh"\n'
        "  end\n"
        "\n"
        "  test do\n"
        '    assert_match version.to_s, shell_output("#{bin}/permesh --version")\n'
        "  end\n"
        "end\n"
    )


def scoop_manifest(version: str, sums: dict) -> dict:
    target = "x86_64-pc-windows-msvc"
    return {
        "version": version,
        "description": "Know who has access to what: local, read-only access review",
        "homepage": REPOSITORY,
        "license": "MIT",
        "architecture": {"64bit": {"url": archive_url(version, target), "hash": sums[target]}},
        "bin": "permesh.exe",
    }


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--version", required=True)
    parser.add_argument("--checksums", required=True, type=Path)
    parser.add_argument("--out", required=True, type=Path)
    args = parser.parse_args(argv)
    try:
        sums = read_checksums(args.checksums, args.version)
    except ValueError as error:
        print(f"error: {error}", file=sys.stderr)
        return 1
    formula = homebrew_formula(args.version, sums)
    manifest = json.dumps(scoop_manifest(args.version, sums), indent=2) + "\n"
    (args.out / "permesh.rb").write_text(formula, encoding="utf-8")
    (args.out / "permesh.json").write_text(manifest, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
